"""Pure renderers for Twinlink-owned systemd, rathole and nftables files.

No renderer touches the host.  The engine validates a complete state, previews
these files and applies the owned nft table as one transaction.  ``running`` is
the desired runtime state; ``enabled`` controls the separate boot lifecycle.
Kernel forwards use a unique per-entry ``relay_port`` on the peer GRE address,
then a second DNAT on VPS2, so no backend route or default route is installed.
"""

from __future__ import annotations

import ipaddress
import json
import re
from pathlib import PurePosixPath

OWNERSHIP_MARKER = "# twinlink-owned"
NFT_TABLE = "twinlink"
MAX_PORT_RANGE = 256
_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,47}\Z")
_INTERFACE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,14}\Z")


def _name(value: str) -> str:
    if not isinstance(value, str) or not _NAME.fullmatch(value):
        raise ValueError("name must contain 1–48 safe letters, digits, dots, dashes or underscores")
    return value


def _interface(value: str) -> str:
    if not isinstance(value, str) or not _INTERFACE.fullmatch(value):
        raise ValueError("unsafe GRE interface name")
    return value


def _ipv4(value: str) -> str:
    try:
        return str(ipaddress.IPv4Address(value))
    except (ValueError, TypeError) as exc:
        raise ValueError("an IPv4 address is required") from exc


def _private(value: str) -> str:
    try:
        return str(ipaddress.IPv4Interface(value).ip)
    except (ValueError, TypeError) as exc:
        raise ValueError("an IPv4 tunnel address is required") from exc


def _path(value: str) -> str:
    if not isinstance(value, str) or not value.startswith("/") or any(ord(c) < 32 or ord(c) == 127 for c in value):
        raise ValueError("generated file and executable paths must be absolute and contain no control characters")
    if ".." in PurePosixPath(value).parts:
        raise ValueError("generated paths may not contain parent traversal")
    return value


def _ports(value: str | int) -> tuple[int, int]:
    raw = str(value)
    if not re.fullmatch(r"[0-9]+(?:-[0-9]+)?", raw):
        raise ValueError("port must be a number or ascending range")
    parts = raw.split("-")
    first, last = int(parts[0]), int(parts[-1])
    if not 1 <= first <= last <= 65535:
        raise ValueError("ports must be between 1 and 65535")
    if last - first + 1 > MAX_PORT_RANGE:
        raise ValueError(f"port ranges may contain at most {MAX_PORT_RANGE} ports")
    return first, last


def _port_text(ports: tuple[int, int]) -> str:
    first, last = ports
    return str(first) if first == last else f"{first}-{last}"


def _quoted(value: str) -> str:
    """A TOML/nft string; input addresses/names are validated before quoting."""
    return json.dumps(value, ensure_ascii=True)


def _systemd_arg(value: str) -> str:
    # systemd performs specifier and environment expansion even without a shell.
    if any(ord(c) < 32 or ord(c) == 127 for c in value):
        raise ValueError("systemd arguments may not contain control characters")
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$")
    return '"' + escaped + '"'


def _command(executable: str, *arguments: str) -> str:
    _path(executable)
    return " ".join(_systemd_arg(item) for item in (executable, *arguments))


def tunnel_unit_name(name: str) -> str:
    return f"twinlink-gre-{_name(name)}.service"


def rathole_unit_name(name: str) -> str:
    return f"twinlink-rathole-{_name(name)}.service"


def rathole_config_path(name: str, state_dir: str = "/var/lib/twinlink") -> str:
    return str(PurePosixPath(_path(state_dir)) / "rathole" / (_name(name) + ".toml"))


def _runtime_arguments(state_dir=None, unit_dir=None, runtime_path=None, rathole_binary=None) -> list[str]:
    arguments = []
    for flag, value in (("--state-dir", state_dir), ("--unit-dir", unit_dir), ("--runtime-path", runtime_path), ("--rathole-binary", rathole_binary)):
        if value is not None:
            arguments += [flag, _path(value)]
    return arguments


def render_tunnel_unit(tunnel: dict, executable: str = "/usr/local/bin/twinlink", *, state_dir=None, unit_dir=None, runtime_path=None, rathole_binary=None) -> str:
    """Render an owned oneshot unit using the engine's safe internal callbacks."""
    name = _name(tunnel["name"])
    globals_ = _runtime_arguments(state_dir, unit_dir, runtime_path, rathole_binary)
    return f"""{OWNERSHIP_MARKER} tunnel={name}
# Generated by twinlink. Change this tunnel through the CLI.
[Unit]
Description=Twinlink GRE tunnel {name}
Wants=network-online.target
After=network-online.target twinlink-restore.service

[Service]
Type=oneshot
User=root
RemainAfterExit=yes
ExecStart={_command(executable, *globals_, "internal", "tunnel-up", name)}
ExecStop={_command(executable, *globals_, "internal", "tunnel-down", name)}
TimeoutStartSec=45
TimeoutStopSec=30
UMask=0077

[Install]
WantedBy=multi-user.target
"""


def render_restore_unit(executable: str = "/usr/local/bin/twinlink", *, state_dir=None, unit_dir=None, runtime_path=None, rathole_binary=None) -> str:
    """Boot restoration revalidates state instead of replaying stale nft files."""
    globals_ = _runtime_arguments(state_dir, unit_dir, runtime_path, rathole_binary)
    return f"""{OWNERSHIP_MARKER} role=restore
# Generated by twinlink. Restores enabled managed entries at boot.
[Unit]
Description=Restore Twinlink managed forwarding
Wants=network-online.target
After=network-online.target

[Service]
Type=oneshot
User=root
RemainAfterExit=yes
ExecStart={_command(executable, *globals_, "internal", "restore")}
TimeoutStartSec=120
UMask=0077

[Install]
WantedBy=multi-user.target
"""


def _rathole_parameters(entry: dict, tunnel: dict) -> tuple[str, str, str, int, int, int]:
    name = _name(entry["name"])
    _name(tunnel["name"])
    if entry.get("tunnel") != tunnel["name"]:
        raise ValueError("forwarding entry belongs to a different tunnel")
    side = entry.get("side", tunnel.get("side"))
    if side not in ("vps1", "vps2") or side != tunnel.get("side"):
        raise ValueError("forwarding and tunnel sides must agree")
    if entry.get("protocol") != "tcp":
        raise ValueError("rathole supports TCP only until this installation passes UDP end-to-end verification")
    bind = _ports(entry["bind_port"])
    destination = _ports(entry["destination_port"])
    if bind[0] != bind[1] or destination[0] != destination[1]:
        raise ValueError("rathole forwarding requires single ports")
    transport = _ports(entry["transport_port"])
    if transport[0] != transport[1]:
        raise ValueError("rathole transport requires a single port")
    token = entry.get("token")
    if not isinstance(token, str) or len(token) < 32 or len(token) > 4096 or any(ord(c) < 32 for c in token):
        raise ValueError("rathole requires a strong per-service token of at least 32 characters")
    return name, side, token, bind[0], destination[0], transport[0]


def render_rathole(entry: dict, tunnel: dict) -> str:
    """One matching TCP service per entry, with the transport confined to GRE."""
    name, side, token, bind, destination, transport = _rathole_parameters(entry, tunnel)
    lines = [f"{OWNERSHIP_MARKER} forward={name}", "# Contains a secret. Keep this file root-owned with mode 0600."]
    role = "server" if side == "vps1" else "client"
    endpoint = _private(tunnel["local_private"] if side == "vps1" else tunnel["remote_private"])
    lines += [f"[{role}]", f'{"bind_addr" if side == "vps1" else "remote_addr"} = {_quoted(f"{endpoint}:{transport}")}', "", f"[{role}.services.{_quoted(name)}]", 'type = "tcp"', f"token = {_quoted(token)}"]
    if side == "vps1":
        service_endpoint = f"{_ipv4(entry['bind_address'])}:{bind}"
        lines.append(f"bind_addr = {_quoted(service_endpoint)}")
    else:
        service_endpoint = f"{_ipv4(entry['destination_address'])}:{destination}"
        lines.append(f"local_addr = {_quoted(service_endpoint)}")
    if entry.get("rathole_transport") == "noise":
        from .rathole import key
        key_name = "local_private_key" if side == "vps1" else "remote_public_key"
        value = key(entry.get("noise_private_key" if side == "vps1" else "noise_public_key"))
        lines += ["", f"[{role}.transport]", 'type = "noise"', "",
                  f"[{role}.transport.noise]", f"{key_name} = {_quoted(value)}"]
    return "\n".join(lines) + "\n"


def render_rathole_unit(entry: dict, tunnel: dict, state_dir: str = "/var/lib/twinlink", binary: str = "/usr/local/bin/rathole") -> str:
    """No shell and no secret argv. Boot ordering is coordinated by restore."""
    name, _, _, _, _, _ = _rathole_parameters(entry, tunnel)
    config = rathole_config_path(name, state_dir)
    # Do not add Requires/BindsTo: a mutation may start this process while the
    # GRE callback/restore job is active. The engine verifies the GRE interface
    # before starting it and orchestrates dependent stops and restarts.
    return f"""{OWNERSHIP_MARKER} forward={name}
# Generated by twinlink. Token is only in the root-readable configuration file.
[Unit]
Description=Twinlink rathole forwarding {name}
After=network-online.target twinlink-restore.service {tunnel_unit_name(tunnel["name"])}

[Service]
Type=simple
User=root
ExecStart={_command(binary, config)}
Restart=always
RestartSec=3
TimeoutStopSec=15
UMask=0077
NoNewPrivileges=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectSystem=strict
ProtectHome=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictAddressFamilies=AF_INET AF_UNIX
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
AmbientCapabilities=CAP_NET_BIND_SERVICE
RestrictSUIDSGID=yes
LockPersonality=yes

[Install]
WantedBy=multi-user.target
"""


def _rule(text: str, name: str, role: str, offset: int | None = None) -> str:
    identity = f"twinlink:{name}:{role}" + (f":{offset}" if offset is not None else "")
    for verdict in (" dnat ", " snat ", " masquerade", " accept"):
        if verdict in text:
            match, action = text.split(verdict, 1)
            text = f"{match} counter{verdict}{action}"
            break
    return f"        {text} comment {_quoted(identity)}"


def _kernel_rules(entry: dict, tunnel: dict, chains: dict[str, list[str]]) -> None:
    name = _name(entry["name"])
    interface = _quoted(_interface(tunnel["interface"]))
    side = entry.get("side", tunnel.get("side"))
    if side not in ("vps1", "vps2") or side != tunnel.get("side"):
        raise ValueError("forwarding and tunnel sides must agree")
    protocol = entry.get("protocol")
    if protocol not in ("tcp", "udp"):
        raise ValueError("kernel forwarding protocol must be TCP or UDP")
    bind = _ports(entry["bind_port"])
    relay = _ports(entry["relay_port"])
    destination = _ports(entry["destination_port"])
    width = bind[1] - bind[0]
    if destination[1] - destination[0] not in (0, width) or width != relay[1] - relay[0]:
        raise ValueError("relay range must match the public range; destination must be a single port or matching range")
    bind_address = _ipv4(entry["bind_address"])
    target = _ipv4(entry["destination_address"])
    local = _private(tunnel["local_private"])
    remote = _private(tunnel["remote_private"])
    if side == "vps1":
        address_match = f"ip daddr {bind_address}" if bind_address != "0.0.0.0" else "fib daddr type local"
        for offset in range(bind[1] - bind[0] + 1):
            match = f"{address_match} {protocol} dport {bind[0] + offset}"
            nat = f"dnat to {remote}:{relay[0] + offset}"
            chains["prerouting"].append(_rule(f"iifname != {interface} {match} {nat}", name, "dnat", offset))
            chains["output"].append(_rule(f"{match} {nat}", name, "local-dnat", offset))
        match = f"oifname {interface} ip daddr {remote} {protocol} dport {_port_text(relay)}"
        chains["postrouting"].append(_rule(f"{match} snat to {local}", name, "snat"))
        chains["forward"].append(_rule(f"{match} ct state new,established accept", name, "forward"))
        chains["forward"].append(_rule(f"iifname {interface} ip saddr {remote} ct state established,related accept", name, "return"))
    else:
        ingress = f"iifname {interface} ip saddr {remote} ip daddr {local}"
        for offset in range(relay[1] - relay[0] + 1):
            destination_port = destination[0] + (offset if destination[0] != destination[1] else 0)
            chains["prerouting"].append(_rule(f"{ingress} {protocol} dport {relay[0] + offset} dnat to {target}:{destination_port}", name, "peer-dnat", offset))
        if target != local:
            match = f"iifname {interface} ip saddr {remote} ip daddr {target} {protocol} dport {_port_text(destination)}"
            chains["postrouting"].append(_rule(f"{match} masquerade", name, "peer-snat"))
            chains["forward"].append(_rule(f"{match} ct state new,established accept", name, "peer-forward"))
            chains["forward"].append(_rule(f"oifname {interface} ip daddr {remote} ct state established,related accept", name, "peer-return"))


def render_nft_entry(entry: dict, tunnel: dict) -> dict[str, list[str]]:
    """Return the expected per-chain rule lines for one kernel entry.

    This helper intentionally ignores runtime flags: callers can use it to
    explain a stopped entry's plan and to determine its expected rule identities.
    """
    chains = {name: [] for name in ("prerouting", "output", "postrouting", "forward")}
    _kernel_rules(entry, tunnel, chains)
    return chains


def expected_nft_comments(state: dict) -> set[str]:
    """Expected active rule identities, suitable for installed-rule inventory."""
    return set(re.findall(r'comment "(twinlink:[^"]+)"', render_nft(state)))


def render_nft(state: dict) -> str:
    """Render only ``table ip twinlink``; caller replaces that owned table.

    This file never flushes rulesets or foreign tables. Accepts here do not
    bypass another firewall's base chains; operators must permit GRE and the
    published traffic in their existing firewall. Conntrack reverses both NAT
    stages for replies, including UDP. One rule per port preserves offsets on
    older nft versions without relying on version-specific NAT map syntax.
    """
    chains = {name: [] for name in ("prerouting", "output", "postrouting", "forward")}
    for name, entry in sorted(state.get("forwards", {}).items()):
        if name != entry.get("name"):
            raise ValueError("forward name does not match its state key")
        if entry.get("mode") != "kernel" or not entry.get("running", False):
            continue
        tunnel = state.get("tunnels", {}).get(entry.get("tunnel"))
        if tunnel is None:
            raise ValueError(f"forward {name} references a missing tunnel")
        if not tunnel.get("running", False):
            continue
        _kernel_rules(entry, tunnel, chains)
    lines = [OWNERSHIP_MARKER + " namespace=ip/twinlink", "# Only this dedicated table is managed by twinlink.", "# The engine replaces this table atomically; no foreign table is flushed.", "# Accept here does not override drops in other firewall base chains.", "table ip twinlink {", '    comment "twinlink-owned"']
    hooks = {"prerouting": "type nat hook prerouting priority dstnat; policy accept;", "output": "type nat hook output priority -100; policy accept;", "postrouting": "type nat hook postrouting priority srcnat; policy accept;", "forward": "type filter hook forward priority filter; policy accept;"}
    for name, rules in chains.items():
        lines += [f"    chain {name} {{", "        " + hooks[name], *rules, "    }"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_files(state: dict, state_dir: str = "/var/lib/twinlink", unit_dir: str = "/etc/systemd/system", executable: str = "/usr/local/bin/twinlink", rathole_binary: str = "/usr/local/bin/rathole") -> dict[str, dict]:
    """Return absolute path -> ``{content: str, mode: int}`` with no I/O.

    Units are 0644; generated rules and secret configurations are 0600. All
    configured entries are materialized so enable/start remains independent.
    The caller creates secret parent directories as root with mode 0700.
    """
    state_dir, unit_dir = _path(state_dir), _path(unit_dir)
    _path(executable)
    _path(rathole_binary)
    files = {}
    runtime_options = {"state_dir": state_dir, "unit_dir": unit_dir, "runtime_path": executable, "rathole_binary": rathole_binary}
    for name, tunnel in sorted(state.get("tunnels", {}).items()):
        if name != tunnel.get("name"):
            raise ValueError("tunnel name does not match its state key")
        files[str(PurePosixPath(unit_dir) / tunnel_unit_name(name))] = {"content": render_tunnel_unit(tunnel, executable, **runtime_options), "mode": 0o644}
    for name, entry in sorted(state.get("forwards", {}).items()):
        if name != entry.get("name"):
            raise ValueError("forward name does not match its state key")
        if entry.get("mode") != "rathole":
            continue
        tunnel = state.get("tunnels", {}).get(entry.get("tunnel"))
        if tunnel is None:
            raise ValueError(f"forward {name} references a missing tunnel")
        files[rathole_config_path(name, state_dir)] = {"content": render_rathole(entry, tunnel), "mode": 0o600}
        files[str(PurePosixPath(unit_dir) / rathole_unit_name(name))] = {"content": render_rathole_unit(entry, tunnel, state_dir, rathole_binary), "mode": 0o644}
    files[str(PurePosixPath(state_dir) / "managed.nft")] = {"content": render_nft(state), "mode": 0o600}
    files[str(PurePosixPath(unit_dir) / "twinlink-restore.service")] = {"content": render_restore_unit(executable, **runtime_options), "mode": 0o644}
    return files
